# A report as reporting systems export them: a title, a units line, two-row
# headers with merged quarter groups, region blocks with subtotals and a
# grand total, a discontinued product on a hidden row, and one figure
# stored as text. Sales are in $000.
import json, sys
import xlsxwriter
from evalkit import excel_saved

work, truth = sys.argv[1], sys.argv[2]
regions = {
    "West": [("Alpha", [120, 980, 131, 1040, 128, 1010, 140, 1120]), ("Bravo", [210, 1650, 220, 1720, 230, 1800, 236, 1870]),
             ("Charlie", [90, 710, 95, 760, 99, 790, 104, 830]), ("Legacy Kit (discontinued)", [40, 300, 35, 260, 0, 0, 0, 0])],
    "North": [("Alpha", [100, 820, 104, 850, 110, 900, 115, 940]), ("Bravo", [60, 470, 58, 455, 62, 490, 66, 520]),
              ("Charlie", [150, 1180, 158, 1250, 160, 1270, 170, 1340])],
    "South": [("Alpha", [80, 640, 84, 670, 86, 690, 90, 720]), ("Bravo", [45, 350, 47, 365, 50, 390, 52, 405]),
              ("Charlie", [130, 1020, 133, 1050, 140, 1100, 146, 1150])],
}
path = f"{work}/regional_sales.xlsx"
wb = xlsxwriter.Workbook(path)
ws = wb.add_worksheet("Report")
bold = wb.add_format({"bold": True})
head = wb.add_format({"bold": True, "align": "center", "bg_color": "#DDEBF7", "border": 1})
num = wb.add_format({"num_format": "#,##0"})
sub = wb.add_format({"bold": True, "num_format": "#,##0", "top": 1})
ws.write("A1", "Regional Sales Report, FY2026", wb.add_format({"bold": True, "font_size": 14}))
ws.write("A2", "Sales in $000 unless stated. Generated by SalesHub 4.2.", wb.add_format({"italic": True}))
ws.merge_range("A4:A5", "Region / Product", head)
for q in range(4):
    ws.merge_range(3, 1 + 2 * q, 3, 2 + 2 * q, f"Q{q + 1}", head)
    ws.write(4, 1 + 2 * q, "Units", head)
    ws.write(4, 2 + 2 * q, "Sales", head)
r = 5
grand = []
for region, products in regions.items():
    ws.write(r, 0, region, bold)
    r += 1
    first = r
    for name, vals in products:
        ws.write(r, 0, "  " + name)
        for j, v in enumerate(vals):
            if region == "South" and name == "Charlie" and j == 3:
                ws.write_string(r, 1 + j, str(v))  # as the export wrote it
            else:
                ws.write_number(r, 1 + j, v, num)
        if "discontinued" in name:
            ws.set_row(r, None, None, {"hidden": True})
        r += 1
    ws.write(r, 0, f"{region} total", bold)
    for j in range(8):
        col = "BCDEFGHI"[j]
        total = sum(v[j] for n, v in products if not (region == "South" and n == "Charlie" and j == 3))
        ws.write_formula(r, 1 + j, f"=SUM({col}{first + 1}:{col}{r})", sub, total)
    grand.append(r + 1)
    r += 2
ws.write(r, 0, "Grand total", bold)
for j in range(8):
    col = "BCDEFGHI"[j]
    total = sum(v[j] for prods in regions.values() for n, v in prods if not (n == "Charlie" and j == 3 and prods is regions["South"]))
    ws.write_formula(r, 1 + j, "=" + "+".join(f"{col}{g}" for g in grand), sub, total)
ws.write(r + 2, 0, "Totals include discontinued lines. Q2 Charlie South was keyed in late.")
ws.set_column("A:A", 28)
ws.freeze_panes(5, 1)
wb.close()
excel_saved(path)
west_q2 = sum(v[3] for n, v in regions["West"] if "discontinued" not in n) * 1000
q2 = {}
for prods in regions.values():
    for n, v in prods:
        if "discontinued" not in n:
            q2[n] = q2.get(n, 0) + v[3]
best = max(q2, key=q2.get)
json.dump({"west_q2": west_q2, "best": best, "q2": q2}, open(truth, "w"))
